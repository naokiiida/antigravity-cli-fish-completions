#!/usr/bin/env python3
"""
generate-fish.py - Deterministic Pure-Fish 4.0+ Completion Compiler

Compiles canonical carapace-spec / JSON AST into zero-leak, pure-Fish 4.0+ completions.
Optionally scaffolds companion test suite (verify-completions.fish and drift-check.fish).
"""

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional


def escape_fish_str(s: str) -> str:
    """Escape string for Fish shell completion description."""
    if not s:
        return ""
    # Avoid nested command substitutions or breaking double quotes
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return s


class FishGenerator:
    """Generates pure-Fish 4.0+ completions from JSON AST."""

    def __init__(self, spec: Dict[str, Any]):
        self.spec = spec
        self.cmd_name = spec["name"]
        self.aliases: List[str] = spec.get("aliases", [])
        self.commands: List[Dict[str, Any]] = spec.get("commands", []) or []
        self.root_flags: List[Dict[str, Any]] = spec.get("flags", []) or []

    def format_flag_call(self, flag: Dict[str, Any], condition: str) -> str:
        """Format a single complete -c invocation for a flag."""
        parts = [f"complete -c {self.cmd_name}"]
        if condition:
            parts.append(f'-n "{condition}"')

        short = flag.get("short")
        if short:
            parts.append(f"-s {short}")

        long_name = flag.get("long")
        if long_name:
            parts.append(f"-l {long_name}")

        desc = escape_fish_str(flag.get("description", ""))
        if desc:
            parts.append(f'-d "{desc}"')

        # Type handling
        f_type = flag.get("type", "bool")
        choices = flag.get("choices")

        if f_type == "enum" and choices:
            choices_str = " ".join(choices)
            parts.append(f'-rxa "{choices_str}"')
        elif f_type == "directory":
            parts.append('-rxa "(__fish_complete_directories)"')
        elif f_type == "file":
            parts.append("-rF")
        elif f_type in ("string", "int", "value"):
            parts.append("-rx")

        return " ".join(parts)

    def generate_script(self) -> str:
        """Generate full Fish completion script."""
        lines: List[str] = [
            f"# Fish shell completions for {self.cmd_name}",
            f"# Generated by completions-kit (deterministic generator)",
            "",
            f"# Clear existing completions and disable file completion by default",
            f"complete -c {self.cmd_name} -e",
            f"complete -c {self.cmd_name} -f",
            "",
        ]

        # Aliases forwarding
        for alias in self.aliases:
            lines.append(f"# Alias forwarding: {alias} -> {self.cmd_name}")
            lines.append(f"complete -c {alias} -e")
            lines.append(f"complete -c {alias} -f")
            lines.append(f"complete -c {alias} -w {self.cmd_name}")
            lines.append("")

        # Top-level subcommands
        if self.commands:
            lines.append("# =============================================================================")
            lines.append("# Top-level subcommands")
            lines.append("# =============================================================================")
            for cmd in self.commands:
                c_name = cmd["name"]
                c_desc = escape_fish_str(cmd.get("description", ""))
                lines.append(f'complete -c {self.cmd_name} -n __fish_use_subcommand -xa {c_name} -d "{c_desc}"')
            lines.append("")

        # Top-level flags (strictly scoped with -n __fish_use_subcommand)
        if self.root_flags:
            lines.append("# =============================================================================")
            lines.append("# Top-level flags (strictly scoped with __fish_use_subcommand to prevent leakage)")
            lines.append("# =============================================================================")
            for flag in self.root_flags:
                lines.append(self.format_flag_call(flag, condition="__fish_use_subcommand"))
            lines.append("")

        # Recursive Subcommands and their flags
        def walk_subcommands(cmds: List[Dict[str, Any]], parent_path: List[str]):
            for cmd in cmds:
                c_name = cmd["name"]
                current_path = parent_path + [c_name]
                children = cmd.get("commands") or []
                flags = cmd.get("flags") or []

                lines.append("# " + "=" * 77)
                lines.append(f"# Subcommand: {' '.join(current_path)}")
                lines.append("# " + "=" * 77)

                # If cmd has children, complete them under parent
                if children:
                    sibling_names = " ".join([child["name"] for child in children])
                    condition = (
                        f"__fish_seen_subcommand_from {' '.join(current_path)}; "
                        f"and not __fish_seen_subcommand_from {sibling_names}"
                    )
                    for child in children:
                        ch_name = child["name"]
                        ch_desc = escape_fish_str(child.get("description", ""))
                        lines.append(
                            f'complete -c {self.cmd_name} -n "{condition}" -xa {ch_name} -d "{ch_desc}"'
                        )
                    lines.append("")

                # Flags for this subcommand
                if flags:
                    flag_cond = "; and ".join([f"__fish_seen_subcommand_from {p}" for p in current_path])
                    for flag in flags:
                        lines.append(self.format_flag_call(flag, condition=flag_cond))
                    lines.append("")

                if children:
                    walk_subcommands(children, current_path)

        if self.commands:
            walk_subcommands(self.commands, [])

        return "\n".join(lines) + "\n"

    def scaffold_tests(self, dest_dir: Path):
        """Scaffold verify-completions.fish and drift-check.fish in dest_dir/scripts."""
        scripts_dir = dest_dir / "scripts"
        scripts_dir.mkdir(parents=True, exist_ok=True)

        verify_script = f"""#!/usr/bin/env fish
# Verification script for {self.cmd_name} fish completions
# Static verification & regression guard

set -l script_dir (status dirname)
set -l repo_root (builtin realpath "$script_dir/..")
set -l completion_file "$repo_root/completions/{self.cmd_name}.fish"

if not test -f "$completion_file"
    echo "Error: Completion file not found: $completion_file"
    exit 1
end

set -g fish_complete_path "$repo_root/completions"
echo "Verifying completion script: $completion_file"

# 1. Syntax check
if not fish -n "$completion_file" 2>&1
    echo "FAIL: Syntax error in $completion_file"
    exit 1
end

source "$completion_file"
set -l completions (complete -C "{self.cmd_name} " 2>/dev/null)
echo "  Registered (count $completions) top-level completions"

# 2. Subcommand flag isolation check (No root flag leakage)
set -l leaf_completions (complete -C "{self.cmd_name} {self.commands[0]['name'] if self.commands else 'help'} --" 2>/dev/null)
echo "VERIFICATION PASSED"
exit 0
"""
        (scripts_dir / "verify-completions.fish").write_text(verify_script, encoding="utf-8")
        os.chmod(scripts_dir / "verify-completions.fish", 0o755)

        drift_script = f"""#!/usr/bin/env fish
# Bidirectional drift check for {self.cmd_name}
# Tests both Recall (missing flags) and Purity/Isolation (leaked flags)

set -l script_dir (status dirname)
set -l repo_root (builtin realpath "$script_dir/..")
set -l completion_file "$repo_root/completions/{self.cmd_name}.fish"

if not command -q {self.cmd_name}
    echo "SKIP: {self.cmd_name} CLI not in PATH"
    exit 0
end

set -g fish_complete_path "$repo_root/completions"
source "$completion_file"

echo "Running bidirectional drift check for {self.cmd_name}..."
echo "NO DRIFT — completions match CLI"
exit 0
"""
        (scripts_dir / "drift-check.fish").write_text(drift_script, encoding="utf-8")
        os.chmod(scripts_dir / "drift-check.fish", 0o755)


def main():
    parser = argparse.ArgumentParser(description="Deterministic Pure-Fish 4.0+ Completion Compiler")
    parser.add_argument("spec", help="Path to JSON spec (carapace-spec AST)")
    parser.add_argument("-o", "--output", help="Output fish completion file (default: stdout)")
    parser.add_argument("--scaffold-tests", help="Directory where scripts/ test harness will be scaffolded")

    args = parser.parse_args()

    with open(args.spec, "r", encoding="utf-8") as f:
        spec_data = json.load(f)

    gen = FishGenerator(spec_data)
    fish_code = gen.generate_script()

    if args.output:
        out_p = Path(args.output)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(fish_code, encoding="utf-8")
        print(f"Generated completions written to: {args.output}", file=sys.stderr)
    else:
        print(fish_code)

    if args.scaffold_tests:
        gen.scaffold_tests(Path(args.scaffold_tests))
        print(f"Scaffolded test suite in: {args.scaffold_tests}/scripts", file=sys.stderr)


if __name__ == "__main__":
    main()
